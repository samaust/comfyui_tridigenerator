import comfy.model_management as model_management
import torch

from ...utils.depth.generation import (
    dav2_infer_metric_depths,
    vda_infer_norm_inv_depths,
)


class TDGenDepthEstimateDepthAnythingV2Metric:
    """
    A ComfyUI node to estimate metric depth using Depth Anything V2 Metric model

    Metric depth is used to estimate shift and scale constants that will be used
    to convert invserse relative depth (generated by Video Depth Anything) to reconstructed metric depth.
    """
    @classmethod
    def INPUT_TYPES(s):
        """
        Defines the input types for the node.
        """
        return {
            "required": {
                # Data
                "images": ("IMAGE",),
                # Model
                "dav2m_model": ("DAV2METRICMODEL", ),
            }
        }

    RETURN_TYPES = (
        "IMAGE",
    )
    RETURN_NAMES = (
        "metric_depths",
    )
    FUNCTION = "run"
    CATEGORY = "TDGen/Depth/Generation"
    DESCRIPTION = "Estimate metric depth using a Depth Anything V2 model."

    def run(
        self,
        images,
        dav2m_model,
    ):
        model = dav2m_model["model"]
        metric_depths = dav2_infer_metric_depths(
            images,
            model,
            dtype=dav2m_model["dtype"],
            device=model_management.get_torch_device(),
        )

        return (metric_depths,)


class TDGenDepthEstimateVideoDepthAnything:
    """
    A ComfyUI node to estimate normalised inverse depth using Video Depth Anything model
    """
    @classmethod
    def INPUT_TYPES(s):
        """
        Defines the input types for the node.
        """
        return {
            "required": {
                # Data
                "images": ("IMAGE",),
                # Model
                "vda_model": ("VDAMODEL", ),
            }
        }

    RETURN_TYPES = (
        "IMAGE",
    )
    RETURN_NAMES = (
        "norm_inv_depths",
    )
    FUNCTION = "run"
    CATEGORY = "TDGen/Depth/Generation"
    DESCRIPTION = "Estimate normalized inverse depth using Video Depth Anything model."

    def run(
        self,
        images,
        vda_model
    ):
        model = vda_model["model"]
        device = model_management.get_torch_device()
        norm_inv_depths = vda_infer_norm_inv_depths(
            images,
            model,
            enable_autocast=vda_model["dtype"] != torch.float32,
            device=device
        )

        return (norm_inv_depths,)
