import os

import folder_paths

from ....utils.videos.load.exr import load_video_exr


class TDGenLoadVideoExr:
    """
    A ComfyUI node to load a video from a .exr file :
    - metric depth video generated by TDGenDepthAnythingV2MetricDepthEstimation
    - depth video generated by TDGenVideoDepthAnythingDepthEstimation
    - any color video
    """
    @classmethod
    def INPUT_TYPES(s):
        """
        Defines the input types for the node.
        """
        allowed_extensions = ["exr"]
        input_dir = folder_paths.get_input_directory()
        files = []
        for f in os.listdir(input_dir):
            if os.path.isfile(os.path.join(input_dir, f)):
                file_parts = f.split('.')
                if len(file_parts) > 1 and (file_parts[-1].lower() in allowed_extensions):
                    files.append(f)
        return {
            "required": {
                # Data
                "video": (sorted(files),),
            }
        }

    RETURN_TYPES = (
        "IMAGE",
    )
    RETURN_NAMES = (
        "images",
    )
    FUNCTION = "run"
    CATEGORY = "TDGen/Videos/Load"
    DESCRIPTION = "Load a video from a .exr file."

    def run(
        self,
        video,
    ):
        # Load video
        load_video_path = folder_paths.get_annotated_filepath(video)
        images = load_video_exr(load_video_path)

        return (images,)
